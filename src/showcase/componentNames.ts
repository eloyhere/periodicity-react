const maps: Readonly<Record<LocaleCode, WordMap>> = {
    "en-GB": {},
    "en-US": {},
    "zh-CN": zh,
    "zh-SG": zh,
    "zh-HK": zh,
    "zh-TW": zh,
    "ja-JP": ja,
    "ko-KR": ko,
    "es-ES": es,
    "es-MX": es,
    "pt-PT": pt,
    "pt-BR": pt,
};

const splitName: (name: string) => string[] = (name: string): string[] =>
    name
        .replace(/^Periodicity/, "")
        .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
        .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2")
        .split(/\s+/)
        .filter(Boolean);

/**
 * Returns an English API name plus its localized component name, for example
 * `Tag 标签` in Simplified Chinese and `Tag タグ` in Japanese.
 * @param name - Public component name such as `Tag` or `DateTimePicker`.
 * @param locale - Active documentation locale.
 * @example
 * localizeComponentName("Tag", "zh-CN"); // "Tag 标签"
 */
export const localizeComponentName: (name: string, locale: LocaleCode) => string = (
    name: string,
    locale: LocaleCode,
): string => {
    const map: WordMap = maps[locale] ?? {};

    if (Object.keys(map).length === 0) {
        return name;
    }

    const bare: string = name.replace(/^Periodicity/, "");
    const direct: string | void = map[bare];

    if (direct !== (void 0)) {
        return `${bare} ${direct}`;
    }

    const words: string[] = splitName(name);
    const translated: string = words
        .map((word: string): string => {
            const singular: string = word.endsWith("s") ? word.slice(0, -1) : word;
            return map[word] ?? map[singular] ?? word;
        })
        .join(locale.startsWith("zh") || locale.startsWith("ja") ? "" : " ");

    return translated === name ? name : `${name} ${translated}`;
};
