    Object.fromEntries(
        (Object.keys(names) as LocaleCode[]).map(
            (locale: LocaleCode): [LocaleCode, Readonly<Record<ThemePresetId, string>>] => [
                locale,
                Object.fromEntries(
                    presetIds.map((id: ThemePresetId, index: number): [ThemePresetId, string] => [
                        id,
                        names[locale][index] ?? id,
                    ]),
                ) as Readonly<Record<ThemePresetId, string>>,
            ],
        ),
    ) as Readonly<Record<LocaleCode, Readonly<Record<ThemePresetId, string>>>>;
