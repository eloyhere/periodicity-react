/**
 * Resolves visible demo chrome copy for the active locale, returning the
 * English source when no translation has been supplied.
 * @param text - English source title, description, or group label.
 * @param locale - Active documentation locale.
 * @example
 * localizeDemoCopy("Card tones", "ja-JP"); // "カードのトーン"
 */
export const localizeDemoCopy: (text: string, locale: LocaleCode) => string = (
    text: string,
    locale: LocaleCode,
): string => dictionaries[locale]?.[text] ?? text;
